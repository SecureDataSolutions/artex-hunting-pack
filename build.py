#!/usr/bin/env python3
"""Regenerate firewall lists, Zeek intel and Suricata IP/DNS rules from iocs.csv.

Usage: python3 build.py   (run from this folder; edit iocs.csv, then rebuild)
"""
import csv
from pathlib import Path

HERE = Path(__file__).parent
rows = list(csv.DictReader(open(HERE / "iocs.csv", newline="")))

out = HERE / "feeds"
out.mkdir(exist_ok=True)

block_ips = sorted({r["indicator"] for r in rows if r["type"] == "ipv4" and r["action"] == "block_and_hunt"},
                   key=lambda s: tuple(int(o) for o in s.split(".")))
hunt_ips = sorted({r["indicator"] for r in rows if r["type"] == "ipv4" and r["action"] == "hunt_only"})
block_domains = sorted({r["indicator"] for r in rows if r["type"] == "domain" and r["action"] == "block_and_hunt"})
hashes = sorted({r["indicator"] for r in rows if r["type"] == "sha256"})

# Firewall external lists (Palo Alto EDL, FortiGate external threat feed, Check Point
# custom intelligence feed and Cisco FMC all accept one-indicator-per-line text).
(out / "edl_block_ipv4.txt").write_text("\n".join(block_ips) + "\n")
(out / "edl_block_domains.txt").write_text("\n".join(block_domains) + "\n")
(out / "hunt_only_ipv4.txt").write_text("\n".join(hunt_ips) + "\n")
(out / "sha256.txt").write_text("\n".join(hashes) + "\n")

# Zeek Intel framework file (tab separated, header required).
zeek_types = {"ipv4": "Intel::ADDR", "domain": "Intel::DOMAIN", "sha256": "Intel::FILE_HASH",
              "user_agent": "Intel::SOFTWARE"}
lines = ["#fields\tindicator\tindicator_type\tmeta.source\tmeta.desc\tmeta.url\tmeta.do_notice"]
for r in rows:
    t = zeek_types.get(r["type"])
    if not t:
        continue
    if r["type"] == "user_agent":
        continue  # too noisy as Intel::SOFTWARE; hunt UAs in KQL/SIEM with app+IP context instead
    desc = f'{r["campaign"]}: {r["context"]}'.replace("\t", " ")
    lines.append("\t".join([r["indicator"], t, r["source"], desc, r["source_url"], "T"]))
(out / "artex_intel.dat").write_text("\n".join(lines) + "\n")

# Suricata rules: IP reputation both directions + DNS/TLS for domains.
sid = 9260001
rules = ["# ARTEX / CyberStrikeAI community rules - generated by build.py from iocs.csv",
         "# Local SID range 9260001-9260999. Rev bump on every rebuild.", ""]
ip_list = ",".join(block_ips)
rules.append(f'alert ip $HOME_NET any -> [{ip_list}] any (msg:"ARTEX-HUNT outbound to published ARTEX/CyberStrikeAI infrastructure"; '
             f'flow:to_server; threshold:type limit, track by_src, count 1, seconds 3600; classtype:trojan-activity; '
             f'metadata:created_at 2026_11_08, tlp clear; sid:{sid}; rev:1;)'); sid += 1
rules.append(f'alert ip [{ip_list}] any -> $HOME_NET any (msg:"ARTEX-HUNT inbound from published ARTEX/CyberStrikeAI infrastructure"; '
             f'threshold:type limit, track by_dst, count 1, seconds 3600; classtype:attempted-recon; '
             f'metadata:created_at 2026_11_08, tlp clear; sid:{sid}; rev:1;)'); sid += 1
for d in block_domains:
    rules.append(f'alert dns $HOME_NET any -> any any (msg:"ARTEX-HUNT DNS query for BLOODALCHEMY C2 {d}"; '
                 f'dns.query; dotprefix; content:".{d}"; endswith; nocase; classtype:trojan-activity; '
                 f'metadata:created_at 2026_11_08, tlp clear; sid:{sid}; rev:1;)'); sid += 1
    rules.append(f'alert tls $HOME_NET any -> $EXTERNAL_NET any (msg:"ARTEX-HUNT TLS SNI BLOODALCHEMY C2 {d}"; '
                 f'tls.sni; dotprefix; content:".{d}"; endswith; nocase; classtype:trojan-activity; '
                 f'metadata:created_at 2026_11_08, tlp clear; sid:{sid}; rev:1;)'); sid += 1
(HERE / "suricata" / "artex_ioc.rules").write_text("\n".join(rules) + "\n")

# Defender XDR / Sentinel IOC hunt, generated so it always matches the feed.
def kql_list(items):
    return ",\n    ".join(f'"{i}"' for i in items)

all_domains = sorted({r["indicator"] for r in rows if r["type"] == "domain"})
kql = f'''// ARTEX / CyberStrikeAI IOC hunt - Microsoft Defender XDR Advanced Hunting
// GENERATED by build.py from iocs.csv. Edit the CSV, not this file.
// Covers BOTH directions and separates allowed from blocked. An allowed connection to any
// of these is an incident; a blocked one is a good day you should still log.
let lookback = 30d;
let BlockIPs = dynamic([
    {kql_list(block_ips)}
]);
let HuntOnlyIPs = dynamic([   // Do not block. VPN exits (only meaningful Oct 15-16 2026 with ConnectWise app context) and unattributed scan-observed ARTEX hosts; see iocs.csv context
    {kql_list(hunt_ips)}
]);
let IOCDomains = dynamic([
    {kql_list(all_domains)}
]);
let Hashes = dynamic([
    {kql_list(hashes)}
]);
union
(
    DeviceNetworkEvents
    | where Timestamp > ago(lookback)
    | where RemoteIP in (BlockIPs) or RemoteIP in (HuntOnlyIPs)
       or RemoteUrl has_any (IOCDomains)
    | extend Direction = iff(ActionType == "InboundConnectionAccepted", "inbound", "outbound"),
             Verdict = case(ActionType in ("ConnectionSuccess", "InboundConnectionAccepted"), "ALLOWED - investigate",
                            ActionType == "ConnectionFailed", "failed/blocked",
                            ActionType),
             Indicator = iff(isnotempty(RemoteUrl) and RemoteUrl has_any (IOCDomains), RemoteUrl, RemoteIP)
    | project Timestamp, Source = "endpoint-net", DeviceName, Direction, Verdict, Indicator,
              RemotePort, LocalIP, InitiatingProcessFileName, InitiatingProcessCommandLine, InitiatingProcessAccountName
),
(
    DeviceEvents
    | where Timestamp > ago(lookback)
    | where ActionType == "DnsQueryResponse"
    | extend Q = tostring(parse_json(AdditionalFields).DnsQueryString)
    | where Q has_any (IOCDomains)
    | project Timestamp, Source = "dns", DeviceName, Direction = "outbound", Verdict = "resolved",
              Indicator = Q, InitiatingProcessFileName, InitiatingProcessCommandLine, InitiatingProcessAccountName
),
(
    DeviceFileEvents
    | where Timestamp > ago(lookback)
    | where SHA256 in (Hashes)
    | project Timestamp, Source = "file", DeviceName, Verdict = ActionType, Indicator = SHA256, FileName, FolderPath,
              InitiatingProcessFileName, InitiatingProcessCommandLine, InitiatingProcessAccountName
)
| order by Timestamp desc
'''
(HERE / "kql").mkdir(exist_ok=True)
(HERE / "kql" / "01_ioc_hunt_defender.kql").write_text(kql)

asim = f'''// ARTEX / CyberStrikeAI IOC hunt - Microsoft Sentinel (ASIM, any network source:
// firewalls, Zeek, Suricata, NSG flow logs...). GENERATED by build.py from iocs.csv.
let lookback = 30d;
let IOCs = dynamic([
    {kql_list(block_ips + hunt_ips)}
]);
_Im_NetworkSession(starttime = ago(lookback), endtime = now())
| where DstIpAddr in (IOCs) or SrcIpAddr in (IOCs)
| extend Direction = iff(DstIpAddr in (IOCs), "outbound", "inbound"),
         Indicator = iff(DstIpAddr in (IOCs), DstIpAddr, SrcIpAddr)
| summarize FirstSeen = min(TimeGenerated), LastSeen = max(TimeGenerated), Events = count(),
            Allowed = countif(DvcAction in~ ("Allow", "Allowed")), Blocked = countif(DvcAction in~ ("Deny", "Drop", "Block", "Reset"))
            by Indicator, Direction, SrcIpAddr, DstIpAddr, DstPortNumber, Dvc, EventProduct, EventVendor
| extend Verdict = iff(Allowed > 0, "ALLOWED - investigate", "blocked/unknown")
| order by Allowed desc, Events desc
'''
(HERE / "kql" / "02_ioc_hunt_sentinel_asim.kql").write_text(asim)

print(f"{len(block_ips)} block IPs, {len(hunt_ips)} hunt-only IPs, {len(block_domains)} domains, "
      f"{len(hashes)} hashes, {sid - 9260001} Suricata rules")
